/**
 * Чому сесію відкликано. У БД — звичайний `text`, а не enum Postgres: нова причина
 * не має коштувати міграції. Закритість множини тримає ось цей TS-юніон.
 *
 * Назовні (`AuthSessionResponse`) причина НЕ віддається: живі сесії причини не мають
 * за визначенням, а мертві в списку не показуються. Це поле для логів і розслідувань.
 */
export type SessionRevokeReason =
  /** Клієнт здав свій токен на /auth/logout */
  | 'logout'
  /** Пред'явлено старий секрет поза вікном ротації — ознака викраденого токена */
  | 'rotation_reuse'
  /** Секрет не збігся з жодним із двох поколінь */
  | 'secret_mismatch'
  /** «Вийти на всіх пристроях» */
  | 'revoke_all'
  /** Пароль змінено (самим юзером або адміном) */
  | 'password_change'
  /** Пароль відновлено через лист (AUTH-3) */
  | 'password_reset'
  /** Адмін вимкнув акаунт — kill-switch */
  | 'user_disabled'
  /** Адмін скинув 2FA (AUTH-4) */
  | 'mfa_reset'
  /** Людина натиснула revoke на конкретному рядку списку пристроїв */
  | 'user';
