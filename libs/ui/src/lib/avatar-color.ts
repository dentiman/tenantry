/** Дешевий детермінований хеш рядка (djb2) — без crypto, без залежностей. */
function hashString(value: string): number {
  let hash = 5381;
  for (let index = 0; index < value.length; index += 1) {
    hash = (hash * 33) ^ value.charCodeAt(index);
  }
  return hash >>> 0;
}

/**
 * 12 курованих якорів OKLCH замість рівномірного повороту hue по колу з ОДНИМ
 * L/C на всі: у OKLCH «жовтий» читається яскравим лише за набагато вищої
 * lightness, ніж «синій»/«фіолетовий» — той самий L/C на hue≈70-110 виходив
 * тьмяно-оливковим/брунатним, а не теплим (спіймано живим прогоном
 * 2026-09-09). Тут у кожного якоря своя lightness/chroma, підібрана під
 * конкретний відтінок — той самий підхід, що в Tailwind-палітрі й у власних
 * `--chart-*` цієї теми. Порядок — по колу, з іменами для читабельності коду,
 * а не семантики (це не токени, споживач їх не бачить).
 */
const AVATAR_PALETTE: readonly { readonly h: number; readonly l: number; readonly c: number }[] = [
  { h: 21, l: 60, c: 0.21 }, // червоний
  { h: 41, l: 66, c: 0.19 }, // помаранчевий
  { h: 70, l: 74, c: 0.16 }, // бурштиновий/золотий
  { h: 111, l: 72, c: 0.18 }, // лаймовий/жовто-зелений
  { h: 145, l: 64, c: 0.16 }, // зелений
  { h: 165, l: 68, c: 0.13 }, // бірюзовий
  { h: 195, l: 68, c: 0.12 }, // блакитний
  { h: 230, l: 62, c: 0.15 }, // небесно-синій
  { h: 258, l: 58, c: 0.19 }, // синій
  { h: 289, l: 58, c: 0.2 }, // фіолетовий
  { h: 320, l: 60, c: 0.2 }, // маджента/рожевий
  { h: 350, l: 60, c: 0.2 }, // рожево-червоний
];

/**
 * Колірний тінт fallback-аватара за ID сутності (юзер чи кастомер): хеш ID →
 * один із 12 курованих hues (`AVATAR_PALETTE`). ID, а не email/імʼя — колір не
 * має «стрибати» при перейменуванні чи зміні пошти.
 *
 * Мікс лише 20% у `--muted` — та сама поверхня, що й дефолтний fallback без
 * тінту, просто з ледь відчутним відтінком (масштаб `--accent`/`--icon`, не
 * Slack/Teams-плитка). База `--muted` вже своя в кожній темі, тож світла тема
 * дає світлий тінт, темна — темний, без окремої пари hex на кожен колір
 * палітри.
 *
 * `in oklab`, а НЕ `in oklch` — та сама конвенція, що в `--icon`/`--accent`/
 * `--event-*-bg` цієї теми, і тут вона не стилістична: світлий `--muted`
 * (`oklch(0.9524 0.0013 286.37)`) має мізерну, але НЕНУЛЬОВУ хрому зі своїм
 * hue (286°, синьо-фіолетовий) — не «powerless» для інтерполятора. У
 * циліндричному `oklch` кут hue мішається пропорційно вазі так само, як L/C,
 * тож 80% ваги `--muted` тягнули результат до лавандового НЕЗАЛЕЖНО від
 * джерела (спіймано живим прогоном 2026-09-09: уся світла тема виходила
 * одним відтінком). `oklab` мішає ректангулярні a/b, де той самий залишковий
 * зсув лише трохи коригує результат, а не перехоплює його hue.
 */
export function getAvatarTint(id: string): string {
  // Фолбек-літерал (перший запис палітри) — суто для noUncheckedIndexedAccess:
  // індекс за побудовою в межах масиву, undefined тут фізично неможливий, а
  // `?? AVATAR_PALETTE[0]` типу не звузив би (той сам індексований)
  const { h, l, c } = AVATAR_PALETTE[hashString(id) % AVATAR_PALETTE.length] ?? {
    h: 21,
    l: 60,
    c: 0.21,
  };
  return `color-mix(in oklab, oklch(${l.toString()}% ${c.toString()} ${h.toString()}) 20%, var(--muted))`;
}
