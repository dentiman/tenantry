import type { ReactNode } from 'react';
import { Separator } from './ui/separator';
import { CrumbTrail, type Crumb } from './page-breadcrumbs';
import { PageHeaderPortal } from './page-header-slot';

export interface PageHeaderProps {
  /** Крихти лівої зони. Взаємовиключні з `children` */
  breadcrumbs?: Crumb[];
  /** Довільна ліва зона замість крихт (тулбар періоду календаря тощо) */
  children?: ReactNode;
  /** Пояснення сторінки — той самий рядок, за крихтами і роздільником */
  subtitle?: ReactNode;
  /** Права зона: головна дія сторінки, перемикачі виглядів */
  actions?: ReactNode;
  /** Назва сторінки для попередження про другий портал у слоті */
  label?: string;
}

/**
 * Хедер СТОРІНКИ, який промальовується в хедері layout-а.
 *
 * ── Навіщо ────────────────────────────────────────────────────────────────────
 * До цього сторінки-списки мали заголовок ДВІЧІ: крихта «Customers» у хедері й
 * `<h1>Customers</h1>` першим рядком контенту. Тепер ідентичність сторінки живе
 * рівно в одному місці — у хедері, — а контент починається одразу з роботи
 * (тулбар фільтрів, таблиця). Головна дія сторінки переїжджає туди ж: у рядку
 * хедера вона стоїть на тій самій висоті, що дзвінок і перемикач теми, і не
 * зʼїдає вертикаль перед таблицею.
 *
 * Тулбар фільтрів у хедер СВІДОМО не переїжджає: він належить таблиці, а не
 * сторінці, і при десятку фільтрів у 56px не вміститься.
 *
 * ── Механіка ──────────────────────────────────────────────────────────────────
 * Це той самий `PageHeaderPortal`, тільки з фіксованою розкладкою «ліва зона /
 * права зона». Портал міняє місце в DOM, але НЕ в дереві React, тому вміст обох
 * зон лишається дитиною сторінки: бачить її контекст (i18n, роутер, QueryClient)
 * і — головне — її СТАН. Саме тому кнопка в `actions` може відкрити модалку,
 * стан якої живе в сторінці, без жодного підняття стану вгору. Деталі й
 * альтернативи, які через це відпали, — у `./page-header-slot.tsx`.
 *
 * Слот у хедері один, тому `PageHeader` і `PageBreadcrumbs` на одному екрані —
 * взаємовиключні; другий портал ловить dev-попередження.
 *
 * ── Підзаголовок — ОДИН рядок із крихтами ─────────────────────────────────────
 * Пояснення стоїть ЗА крихтами, через вертикальний роздільник, сірим. Другий
 * рядок під ними був спробуваний і знятий: хедер має фіксовану `h-14`, і два
 * рядки в ньому або зсувають крихти з центру (ламаючи неперервну лінію, яку
 * складають три `h-14` — шапка рейлу, шапка колонки, хедер), або мусять висіти
 * `absolute` в 18px, що лишаються знизу. Обидва варіанти платять розкладкою за
 * текст, який є довідкою, а не заголовком.
 *
 * В одному рядку ієрархія читається сама: «де я» (крихти, звичайний колір) —
 * роздільник — «що це» (пояснення, `muted`). Роздільник ВЕРТИКАЛЬНИЙ, а не
 * крапка: крапкою вже розділені крихти між собою (`›`), і два роздільники
 * різної природи не плутаються.
 *
 * Пояснення гнеться першим (`min-w-0 truncate`), крихти не стискаються ніколи:
 * втратити «Settings › General» гірше, ніж хвіст довідкового речення.
 */
export function PageHeader({ breadcrumbs, children, subtitle, actions, label }: PageHeaderProps) {
  return (
    <PageHeaderPortal label={label}>
      <div className="flex w-full min-w-0 items-center justify-between gap-3">
        <div className="flex min-w-0 flex-1 items-center gap-2">
          {/* shrink-0: стискається пояснення, а не «де я» */}
          <div className="shrink-0">{breadcrumbs ? <CrumbTrail items={breadcrumbs} /> : children}</div>
          {subtitle ? (
            <>
              {/* `data-vertical:self-center`, а НЕ голий `self-center`: у
                  вендереному `separator` базовий клас — `data-vertical:self-stretch`,
                  і tailwind-merge лишає обидва (різні модифікатори), а виграє
                  атрибутний селектор. `stretch` при заданій `h-4` не розтягує
                  нічого — він поводиться як `flex-start`, і риска тулилась до
                  ВЕРХУ рядка. Модифікатор мусить збігтися, щоб клас замінився.

                  `translate-y-px` — вирівнювання по ОСІ ТЕКСТУ, а не по боксу
                  рядка: line-height лишає над великими літерами більше повітря,
                  ніж під ними, тож геометрично центрована риска читається
                  задертою. `/60` — цей роздільник слабший за межу поверхні: він
                  ділить два шматки ОДНОГО рядка, а не дві площини */}
              <Separator
                orientation="vertical"
                className="h-4 translate-y-px bg-border/60 data-vertical:self-center"
              />
              <p className="min-w-0 truncate text-sm text-muted-foreground">{subtitle}</p>
            </>
          ) : null}
        </div>

        {actions ? <div className="flex shrink-0 items-center gap-2">{actions}</div> : null}
      </div>
    </PageHeaderPortal>
  );
}
